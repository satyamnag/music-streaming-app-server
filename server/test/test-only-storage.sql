-- ============================================================================
-- TEST-ONLY storage emulation table for the real-PostgreSQL adapter.
-- ============================================================================
-- WHY THIS FILE EXISTS
--
-- The real-DB harness (test/real-supabase-adapter.mjs) emulates Supabase Storage
-- with a genuine Postgres table holding genuine bytes, so the suite can prove
-- documents round-trip through storage as real ciphertext. That adapter reads
-- and writes `public.test_only_storage_objects`.
--
-- That table had NO DDL ANYWHERE IN THE REPOSITORY. The suite only ran because a
-- previous session created it by hand in a long-lived test database, so a fresh
-- checkout following the documented steps failed with:
--
--     error: relation "public.test_only_storage_objects" does not exist
--
-- That is a reproducibility defect, not a product defect: it meant "the E2E
-- passes" could not be reproduced from the repo. This file makes the setup
-- complete and repeatable.
--
-- Apply AFTER the Supabase shim and BEFORE the migrations:
--
--   psql -p 55432 -U postgres -d sb_partner_test -v ON_ERROR_STOP=1 \
--     -f server/test/supabase-shim.sql \
--     -f server/test/test-only-storage.sql \
--     -f server/migrations/003_referrals.sql \
--     ... \
--     -f server/migrations/033_partner_program.sql \
--     -f server/migrations/034_partner_document_access_log.sql
--
-- WHAT THE ADAPTER REQUIRES, and why each column is here:
--   bucket_id, name   the object identity
--   data              the raw bytes (bytea) — the ciphertext, not a path
--   content_type      what the upload declared
--   unique (bucket_id, name)
--                     REQUIRED: storage.upload({ upsert: false }) is an
--                     INSERT ... ON CONFLICT, and without this constraint
--                     PostgreSQL rejects the statement with 42P10. The
--                     upsert:false path is what proves a document cannot be
--                     silently overwritten, so the constraint is load-bearing.
--
-- THIS TABLE IS NOT PART OF THE PRODUCT SCHEMA. It lives only in test
-- databases; never apply it to a deployment. `test_only_` is deliberate so it is
-- unmistakable in a table listing.
-- ============================================================================

create table if not exists public.test_only_storage_objects (
  id bigint generated by default as identity primary key,
  bucket_id text not null,
  name text not null,
  data bytea not null,
  content_type text,
  created_at timestamptz not null default now(),
  unique (bucket_id, name)
);

-- The adapter deletes by (bucket, name) in bulk during cleanup and by key on
-- download, so an index on the pair keeps that cheap once a run has uploaded
-- several documents.
create index if not exists test_only_storage_objects_bucket_name_idx
  on public.test_only_storage_objects (bucket_id, name);
